/// One quality row in the picker's list.
class ZmixQualityOption {
  const ZmixQualityOption({
    required this.url,
    required this.quality,
    required this.videoOnly,
    required this.height,
    required this.bitrate,
    required this.codec,
  });

  final String url;

  /// Display label ('360p', '720p', ...).
  final String quality;

  /// True = needs the external audio track (adaptive split stream).
  final bool videoOnly;
  final int height;
  final int bitrate;

  /// Codec string kept for selection ranking, not shown.
  final String codec;
}

typedef ZmixStreamChoices = ({
  List<ZmixQualityOption> qualities,
  String? audioUrl,
  /// Headers matching the API client that produced these URLs (see
  /// stream_headers.dart). Null when that client declares none.
  Map<String, String>? httpHeaders,
});

/// One subtitle language a video offers, deduplicated to a single track.
class ZmixCaptionTrack {
  const ZmixCaptionTrack({
    required this.code,
    required this.name,
    required this.autoGenerated,
    required this.info,
  });

  /// ISO 639-1 code ('ar', 'en-US', ...).
  final String code;

  /// YouTube's English language name, may be empty.
  final String name;
  final bool autoGenerated;

  /// Handle used to fetch the actual cues.
  final ClosedCaptionTrackInfo info;
}

/// Thin wrapper over youtube_explode_dart for the library flows.
class YoutubeService {
  /// [manifestFetcher] is a test seam for [resolveStreamChoices]: when given,
  /// it replaces the network call (one call per API client). Production code
  /// passes nothing.
  YoutubeService({
    Future<StreamManifest> Function(String videoId, YoutubeApiClient client)?
        manifestFetcher,
  })  : _yt = YoutubeExplode(),
        _manifestFetcher = manifestFetcher;

  final Future<StreamManifest> Function(String videoId, YoutubeApiClient client)?
      _manifestFetcher;

  final YoutubeExplode _yt;

  /// Fetches a playlist's real metadata and video list from YouTube.
  /// Throws [FormatException] when the link is not a playlist link.
  Future<LibraryPlaylist> fetchPlaylist(
    String input, {
    String? nickname,
    void Function(int fetched)? onProgress,
    bool Function()? isCancelled,
  }) async {
    final parsed = PlaylistId.parsePlaylistId(input.trim());
    if (parsed == null) {
      throw const FormatException('مش قادر أفهم الرابط ده كقائمة تشغيل يوتيوب');
    }
    final playlist = await _yt.playlists.get(PlaylistId(parsed));
    // youtube_explode's getVideos yields nothing since YouTube moved playlist
    // pages to lockupViewModel (verified 2026-11-25); ZMIX fetches the list
    // itself from the same public endpoint the website uses.
    final fetcher = PlaylistFetcher();
    final FetchResult result;
    try {
      result = await fetcher.fetchVideos(
        playlist.id.value,
        onProgress: onProgress,
        isCancelled: isCancelled,
      );
    } finally {
      fetcher.close();
    }
    final videos = result.videos;
    // Honest count handling: the fetcher follows YouTube's own
    // "show unavailable videos" view, so a complete import contains every
    // entry the site can serve, hidden ones flagged. A residual guard
    // remains: if the served total still falls short of YouTube's declared
    // header count, surface that as its own state instead of implying the
    // library holds every video. Import completeness is about the entry
    // list; whether any entry actually plays is decided at playback time.
    final declared = playlist.videoCount;
    var complete = result.complete;
    String? note = result.stopReason;
    if (result.complete &&
        declared != null &&
        videos.length < declared &&
        (declared - videos.length) > 2) {
      complete = false;
      note = 'short_of_declared';
    }
    final name = (nickname != null && nickname.trim().isNotEmpty)
        ? nickname.trim()
        : playlist.title;
    return LibraryPlaylist(
      id: playlist.id.value,
      name: name,
      url: playlist.url,
      author: playlist.author,
      thumbUrl: videos.isNotEmpty
          ? videos.first.thumbUrl
          : playlist.thumbnails.highResUrl,
      videos: videos,
      addedAt: DateTime.now(),
      importComplete: complete,
      totalCountHint: playlist.videoCount,
      importNote: note,
      hiddenUntitledCount: result.hiddenUntitled,
      hiddenTitledCount: result.hiddenTitled,
    );
  }

  /// Resolves a playable muxed stream URL for a video.
  /// All muxed (audio+video in one file) qualities, best first. Muxed-only
  /// keeps one-URL-per-quality switching simple; adaptive split streams are
  /// not exposed yet.
  Future<List<({String url, String quality})>> resolvePlayableList(
      String videoId) async {
    final manifest = await _yt.videos.streamsClient.getManifest(VideoId(videoId));
    if (manifest.muxed.isEmpty) {
      throw const FormatException('مفيش صيغة تشغيل مدمجة متاحة للفيديو ده');
    }
    final streams = manifest.muxed.toList()
      ..sort((a, b) => b.bitrate.bitsPerSecond.compareTo(a.bitrate.bitsPerSecond));
    return [
      for (final s in streams)
        (url: s.url.toString(), quality: _qualityLabel(s.videoQuality.name)),
    ];
  }

  /// Every quality the player offers.
  ///
  /// 0.3.4 offered adaptive video-only streams (played with the audio
  /// track from [ZmixStreamChoices.audioUrl]); every adaptive pick failed
  /// on the user's device with mpv 'Failed to open' (4 screenshots,
  /// 2026-11-25) while muxed 360p played. 0.3.5 therefore passed
  /// `videoOnly: const []`.
  ///
  /// 0.3.6-diag RE-ENABLES the adaptive entries as an experiment under the
  /// user-authorized diagnostic build (2026-11-26): they are offered again
  /// so the diagnostics log can capture exactly where they fail on device
  /// (extraction vs open vs audio attach), NOT because they are fixed.
  /// The cause is still unverified (see Diagnostics in Settings).
  Future<ZmixStreamChoices> resolveStreamChoices(String videoId,
      {String? attemptId}) async {
    Diag.I.outcome('بداية استخراج صيغ التشغيل',
        stage: 'extract', attemptId: attemptId);
    final StreamManifest manifest;
    final YoutubeApiClient usedClient;
    try {
      // Same behavior as the library default (androidSdkless, then tv) but
      // each call names ONE client, so every URL below has known provenance.
      final r = await fetchWithProvenance<StreamManifest>(
          (c) => _manifestFetcher != null
              ? _manifestFetcher(videoId, c)
              : _yt.videos.streamsClient
                  .getManifest(VideoId(videoId), ytClients: [c]),
          (m) => m.streams.isEmpty);
      manifest = r.manifest;
      usedClient = r.client;
      Diag.I.outcome('عميل الاستخراج',
          stage: 'extract',
          attemptId: attemptId,
          detail: '${usedClient.payload['context']['client']['clientName']}');
    } catch (e) {
      Diag.I.outcome('فشل استخراج صيغ التشغيل',
          stage: 'extract', ok: false, detail: '$e', attemptId: attemptId);
      rethrow;
    }
    if (manifest.muxed.isEmpty && manifest.videoOnly.isEmpty) {
      Diag.I.outcome('لا توجد صيغ تشغيل إطلاقًا',
          stage: 'extract', ok: false, attemptId: attemptId);
      throw const FormatException('مفيش صيغة تشغيل متاحة للفيديو ده');
    }
    final audioUrl = pickAudioUrl([
      for (final s in manifest.audioOnly)
        (
          url: s.url.toString(),
          bitrate: s.bitrate.bitsPerSecond,
          mime: s.codec.mimeType,
        ),
    ]);
    Diag.I.outcome(
      'اكتمل استخراج الصيغ',
      stage: 'extract',
      attemptId: attemptId,
      detail: 'muxed=${manifest.muxed.length} '
          'videoOnly=${manifest.videoOnly.length} '
          'audioOnly=${manifest.audioOnly.length} '
          'audioPicked=${audioUrl != null ? 'نعم' : 'لا'}',
    );
    final qualities = buildQualityChoices(
      // A video-only stream without a paired audio URL would play
      // SILENT: never offer it; the muxed entries remain as the fallback.
      hasAudio: audioUrl != null,
      muxed: [
        for (final s in manifest.muxed)
          (
            url: s.url.toString(),
            height: s.videoResolution.height,
            bitrate: s.bitrate.bitsPerSecond,
            codec: s.videoCodec,
          ),
      ],
      // Re-enabled experimentally in 0.3.6-diag (doc comment above).
      videoOnly: [
        for (final s in manifest.videoOnly)
          (
            url: s.url.toString(),
            height: s.videoResolution.height,
            bitrate: s.bitrate.bitsPerSecond,
            codec: s.videoCodec,
          ),
      ],
    );
    if (Diag.I.verbose) {
      for (final q in qualities) {
        Diag.I.outcome(
          'جودة معروضة ${q.quality}',
          stage: 'extract',
          attemptId: attemptId,
          detail: '${q.videoOnly ? 'منفصلة' : 'مدمجة'} '
              'codec=${q.codec.split('.').first} '
              'host=${Diag.hostOf(q.url)}',
        );
      }
    }
    return (
      qualities: qualities,
      audioUrl: audioUrl,
      httpHeaders: streamHeadersFor(usedClient),
    );
  }

  /// Pure: merges muxed and adaptive entries into the picker's list, one
  /// entry per resolution height, best first. Per height: a muxed stream
  /// wins (no external audio needed); among video-only candidates avc1 wins
  /// (hardware-decodable on phones), then higher bitrate.
  static List<ZmixQualityOption> buildQualityChoices({
    required List<({String url, int height, int bitrate, String codec})> muxed,
    required List<({String url, int height, int bitrate, String codec})> videoOnly,
    required bool hasAudio,
  }) {
    final byHeight = <int, ZmixQualityOption>{};
    int codecRank(String codec) => codec.startsWith('avc1') ? 0 : 1;
    for (final s in [...muxed.map((m) => (s: m, videoOnly: false)), ...videoOnly.map((v) => (s: v, videoOnly: true))]) {
      // Guard: no paired audio -> drop video-only candidates entirely.
      if (s.videoOnly && !hasAudio) continue;
      final candidate = ZmixQualityOption(
        url: s.s.url,
        quality: '${s.s.height}p',
        videoOnly: s.videoOnly,
        height: s.s.height,
        bitrate: s.s.bitrate,
        codec: s.s.codec,
      );
      final existing = byHeight[s.s.height];
      if (existing == null ||
          (existing.videoOnly && !candidate.videoOnly) ||
          (existing.videoOnly == candidate.videoOnly &&
              (codecRank(candidate.codec) < codecRank(existing.codec) ||
                  (codecRank(candidate.codec) == codecRank(existing.codec) &&
                      candidate.bitrate > existing.bitrate)))) {
        byHeight[s.s.height] = candidate;
      }
    }
    final out = byHeight.values.toList()
      ..sort((a, b) => b.height.compareTo(a.height));
    return out;
  }

  /// Pure: picks the audio track for adaptive playback — highest-bitrate
  /// mp4 (m4a) when present, else highest bitrate overall.
  static String? pickAudioUrl(
      List<({String url, int bitrate, String mime})> audioOnly) {
    if (audioOnly.isEmpty) return null;
    final sorted = [...audioOnly]
      ..sort((a, b) => b.bitrate.compareTo(a.bitrate));
    final mp4 = sorted.where((a) => a.mime.startsWith('audio/mp4'));
    return (mp4.isNotEmpty ? mp4.first : sorted.first).url;
  }

  Future<({String url, String quality})> resolvePlayable(String videoId,
      {String? attemptId}) async {
    Diag.I.outcome('بداية استخراج صيغة مدمجة',
        stage: 'extract', attemptId: attemptId);
    final StreamManifest manifest;
    try {
      manifest = await _yt.videos.streamsClient.getManifest(VideoId(videoId));
    } catch (e) {
      Diag.I.outcome('فشل استخراج الصيغة المدمجة',
          stage: 'extract', ok: false, detail: '$e', attemptId: attemptId);
      rethrow;
    }
    if (manifest.muxed.isEmpty) {
      Diag.I.outcome('لا توجد صيغة مدمجة',
          stage: 'extract', ok: false, attemptId: attemptId);
      throw const FormatException('مفيش صيغة تشغيل مدمجة متاحة للفيديو ده');
    }
    final stream = pickBestMuxed(manifest);
    Diag.I.outcome('اكتمل استخراج الصيغة المدمجة',
        stage: 'extract',
        attemptId: attemptId,
        detail: 'muxed=${manifest.muxed.length} '
            'videoOnly=${manifest.videoOnly.length} '
            'audioOnly=${manifest.audioOnly.length}');
    return (url: stream.url.toString(), quality: _qualityLabel(stream.videoQuality.name));
  }

  /// Pure: the muxed stream with the highest bitrate. The manifest MUST be
  /// statically typed: `withHighestBitrate` is an extension method, so a
  /// `dynamic` receiver throws NoSuchMethodError at runtime (0.3.6-diag
  /// regression: an untyped `late final manifest` made every call dynamic).
  static MuxedStreamInfo pickBestMuxed(StreamManifest manifest) =>
      manifest.muxed.withHighestBitrate();

  /// 'medium360' -> '360p'
  static String _qualityLabel(String raw) {
    final match = RegExp(r'(\d+)').firstMatch(raw);
    return match == null ? raw : '${match.group(1)}p';
  }

  /// Subtitle languages available for a video, one entry per language code
  /// (YouTube lists the same language once per internal format; a manual
  /// track wins over an auto-generated one for the same code). Empty when
  /// the video has no captions at all — the UI drops its button then rather
  /// than promising a subtitle that cannot load.
  Future<List<ZmixCaptionTrack>> captionTracks(String videoId) async {
    final manifest =
        await _yt.videos.closedCaptions.getManifest(VideoId(videoId));
    final byCode = <String, ZmixCaptionTrack>{};
    for (final t in manifest.tracks) {
      final existing = byCode[t.language.code];
      if (existing == null || (existing.autoGenerated && !t.isAutoGenerated)) {
        byCode[t.language.code] = ZmixCaptionTrack(
          code: t.language.code,
          name: t.language.name,
          autoGenerated: t.isAutoGenerated,
          info: t,
        );
      }
    }
    return byCode.values.toList();
  }

  /// Fetches one track's cues and renders them as SRT for media_kit's
  /// external-subtitle loader.
  Future<String> captionSrt(ZmixCaptionTrack track) async {
    final full = await _yt.videos.closedCaptions.get(track.info);
    return captionsToSrt([
      for (final c in full.captions)
        (text: c.text, start: c.offset, end: c.offset + c.duration),
    ]);
  }

  void close() => _yt.close();
}
