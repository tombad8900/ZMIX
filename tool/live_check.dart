import 'dart:io';
import 'package:zmix/playlist_fetcher.dart';
import 'package:zmix/youtube_service.dart';

Future<void> main(List<String> args) async {
  final fetcher = PlaylistFetcher();
  final result = await fetcher.fetchVideos(args[0]);
  fetcher.close();
  final visible = result.videos.where((v) => v.visibility == 'visible').take(3).toList();
  stdout.writeln('playlist videos: ${result.videos.length}, sampling ${visible.length}');
  final service = YoutubeService();
  for (final v in visible) {
    try {
      final c = await service.resolveStreamChoices(v.id);
      stdout.writeln('${v.id}: qualities=[${c.qualities.map((q) => '${q.quality}${q.videoOnly ? "(v-only)" : "(muxed)"}').join(', ')}] audio=${c.audioUrl != null ? "yes" : "NO"}');
    } catch (e) {
      stdout.writeln('${v.id}: ERROR ${e.runtimeType}');
    }
  }
  // Caption e2e: download + convert a real track to SRT.
  try {
    final tracks = await service.captionTracks(visible.first.id);
    stdout.writeln('captions for ${visible.first.id}: ${tracks.map((t) => '${t.code}${t.autoGenerated ? "(auto)" : ""}').join(', ')}');
    if (tracks.isNotEmpty) {
      final srt = await service.captionSrt(tracks.first);
      stdout.writeln('SRT bytes: ${srt.length}');
      stdout.writeln(srt.split('\n').take(8).join('\n'));
    }
  } catch (e) {
    stdout.writeln('captions ERROR ${e.runtimeType}');
  }
  service.close();
}
