// Local diagnostic (not shipped): probe YouTube caption availability and the
// raw caption data shape for a sample of a playlist's videos. Pass the
// playlist id as an argument; nothing is recorded in the repo.
import 'dart:io';

import 'package:youtube_explode_dart/youtube_explode_dart.dart';
import 'package:zmix/playlist_fetcher.dart';

Future<void> main(List<String> args) async {
  if (args.isEmpty) {
    stderr.writeln('usage: dart run tool/caption_probe.dart <playlistId> [sampleSize]');
    exitCode = 2;
    return;
  }
  final playlistId = args[0];
  final sampleSize = args.length > 1 ? int.parse(args[1]) : 12;

  final fetcher = PlaylistFetcher();
  final result = await fetcher.fetchVideos(playlistId);
  fetcher.close();

  final sample = result.videos
      .where((v) => v.visibility == 'visible')
      .take(sampleSize)
      .toList();
  stdout.writeln('sampled ${sample.length} of ${result.videos.length}');

  final yt = YoutubeExplode();
  var withTracks = 0;
  var arabic = 0;
  String? demoId;
  for (final v in sample) {
    try {
      final manifest = await yt.videos.closedCaptions.getManifest(VideoId(v.id));
      if (manifest.tracks.isEmpty) {
        stdout.writeln('NO-TRACKS  ${v.id}  ${v.title}');
        continue;
      }
      withTracks++;
      final langs = [
        for (final t in manifest.tracks)
          '${t.language.code}${t.isAutoGenerated ? "(auto)" : ""}'
      ];
      if (manifest.tracks.any((t) => t.language.code.startsWith('ar'))) {
        arabic++;
      }
      demoId ??= v.id;
      stdout.writeln('TRACKS     ${v.id}  $langs  ${v.title}');
    } catch (e) {
      stdout.writeln('ERROR      ${v.id}  ${e.runtimeType}  ${v.title}');
    }
  }
  stdout.writeln('SUMMARY: $withTracks/${sample.length} have captions, $arabic have Arabic');

  if (demoId != null) {
    final manifest = await yt.videos.closedCaptions.getManifest(VideoId(demoId));
    final track = manifest.tracks.firstWhere(
      (t) => t.language.code.startsWith('ar'),
      orElse: () => manifest.tracks.first,
    );
    stdout.writeln('--- demo track: ${track.language.code} '
        'auto=${track.isAutoGenerated} fmt=${track.format} ---');
    final full = await yt.videos.closedCaptions.get(track);
    stdout.writeln('captions: ${full.captions.length}');
    for (final c in full.captions.take(12)) {
      stdout.writeln('[${c.offset.inMilliseconds}+${c.duration.inMilliseconds}] '
          'parts=${c.parts.length} "${c.text.replaceAll('\n', ' / ')}"');
      for (final p in c.parts) {
        stdout.writeln('    part[${p.offset.inMilliseconds}] "${p.text}"');
      }
    }
  }
  yt.close();
}
